/** Find a specific industry with aliases and normalized labels. */
export function getHomepageImage(nicheOrLabel) {
  const norm = value => String(value || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  const target = norm(nicheOrLabel);
  const ALIASES = {epoxyflooring: 'epoxy', cleaningservices: 'cleaning', autodetailing: 'autodetailing', electrician: 'electrical'};
  const desired = norm(ALIASES[target] || target);
  return HOMEPAGE_INDUSTRY_IMAGES.find(item =>
    norm(item.id) === desired || norm(item.niche) === desired || norm(item.label) === desired) || null;
}

export function getAllHomepageImages() {
  return HOMEPAGE_INDUSTRY_IMAGES;
}
