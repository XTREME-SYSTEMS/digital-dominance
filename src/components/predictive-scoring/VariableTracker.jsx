import React, { useState, useEffect, useCallback } from "react";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { base44 } from "@/api/base44Client";
import {
  CheckSquare, Square, SlidersHorizontal, CloudRain, Save, History,
  TrendingUp, TrendingDown, Minus, Loader2, Award, Activity
} from "lucide-react";

const CONTROL_VARIABLES = [
  { id: "followup_speed", label: "Follow-Up Speed", desc: "Contact leads within 4 hours of submission", impact: "Up to +15% conversion" },
  { id: "deal_size_upsell", label: "Deal Size / Upsell", desc: "Push premium systems (metallic, polyaspartic)", impact: "+10-40% revenue per booking" },
  { id: "source_prioritization", label: "Source Prioritization", desc: "Focus on paid and referral sources over organic", impact: "+5-12% conversion boost" },
  { id: "sales_effort_allocation", label: "Sales Effort Allocation", desc: "Route HOT leads (90+) to top closers first", impact: "Maximizes high-probability deals" },
  { id: "contact_frequency", label: "Contact Frequency", desc: "Multi-touch sequence: call + email + SMS within 48h", impact: "+20% contact rate" },
  { id: "pricing_strategy", label: "Pricing Strategy", desc: "Offer financing or bundle discounts to close faster", impact: "Reduces lost-to-no-decision" },
  { id: "script_quality", label: "Script Quality", desc: "Use score-aware scripts (urgency for HOT, education for COOL)", impact: "Improves per-lead conversion" },
  { id: "salesperson_skill", label: "Salesperson Skill", desc: "Assign trained closers to high-value leads", impact: "Direct conversion multiplier" },
  { id: "lead_response_channel", label: "Response Channel", desc: "Match channel to lead preference (phone vs text vs email)", impact: "Increases engagement" },
  { id: "appointment_setting", label: "Appointment Setting", desc: "Book in-home estimates during first contact", impact: "Advances pipeline stage" },
];

const UNCONTROLLABLE_VARIABLES = [
  { id: "market_demand", label: "Market Demand", desc: "Seasonal interest in epoxy/concrete services", impact: "Affects lead volume and intent" },
  { id: "competitor_pricing", label: "Competitor Pricing", desc: "Rival contractors undercutting or premium positioning", impact: "Affects win rate on estimates" },
  { id: "seasonality", label: "Seasonality", desc: "Spring/summer surge, winter slowdown", impact: "Lead volume varies 3-5x" },
  { id: "economic_conditions", label: "Economic Conditions", desc: "Consumer spending power, interest rates, housing market", impact: "Affects deal size and close rate" },
  { id: "weather", label: "Weather", desc: "Rain/extreme temps delay installations and consultations", impact: "Pushes bookings to later weeks" },
  { id: "lead_volume", label: "Lead Volume", desc: "Total leads generated by marketing each period", impact: "More leads = more opportunities but dilution" },
  { id: "google_algorithm", label: "Google Algorithm Changes", desc: "Search ranking shifts affect organic lead quality", impact: "Changes source mix over time" },
  { id: "customer_budget", label: "Customer Budget Constraints", desc: "What the homeowner can actually afford", impact: "Caps deal size regardless of pitch" },
  { id: "competitor_ad_spend", label: "Competitor Ad Spend", desc: "Rivals increasing Google Ads budget in your area", impact: "Increases your cost-per-lead" },
  { id: "material_costs", label: "Material Costs", desc: "Epoxy/resin price fluctuations from suppliers", impact: "Squeezes margin on booked jobs" },
];

export default function VariableTracker({ lastSimulation }) {
  const queryClient = useQueryClient();
  const [controlChecked, setControlChecked] = useState([]);
  const [uncontrolChecked, setUncontrolChecked] = useState([]);
  const [saving, setSaving] = useState(false);
  const [savingSnapshot, setSavingSnapshot] = useState(false);

  // Load saved checklist state
  const { data: checklistRecord } = useQuery({
    queryKey: ["sim-tracking-checklist"],
    queryFn: async () => {
      const res = await base44.entities.SimulationTracking.filter(
        { tracking_type: "variable_checklist" },
        { sort: "-created_date", limit: 1 }
      );
      return res.items?.[0] || null;
    },
  });

  // Load simulation history
  const { data: history = [], isLoading: historyLoading } = useQuery({
    queryKey: ["sim-tracking-history"],
    queryFn: async () => {
      const res = await base44.entities.SimulationTracking.filter(
        { tracking_type: "simulation_snapshot" },
        { sort: "-created_date", limit: 20 }
      );
      return res.items || [];
    },
  });

  useEffect(() => {
    if (checklistRecord) {
      setControlChecked(checklistRecord.control_variables_checked || []);
      setUncontrolChecked(checklistRecord.uncontrollable_variables_checked || []);
    }
  }, [checklistRecord]);

  const toggleControl = (id) => {
    setControlChecked((prev) => prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id]);
  };
  const toggleUncontrol = (id) => {
    setUncontrolChecked((prev) => prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id]);
  };

  const saveChecklist = async () => {
    setSaving(true);
    try {
      const payload = {
        tracking_type: "variable_checklist",
        control_variables_checked: controlChecked,
        uncontrollable_variables_checked: uncontrolChecked,
      };
      if (checklistRecord?.id) {
        await base44.entities.SimulationTracking.update(checklistRecord.id, payload);
      } else {
        await base44.entities.SimulationTracking.create(payload);
      }
      queryClient.invalidateQueries({ queryKey: ["sim-tracking-checklist"] });
    } catch (e) {
      alert("Failed to save: " + e.message);
    } finally {
      setSaving(false);
    }
  };

  const saveSnapshot = async () => {
    if (!lastSimulation?.ok) return;
    setSavingSnapshot(true);
    try {
      await base44.entities.SimulationTracking.create({
        tracking_type: "simulation_snapshot",
        simulations_run: lastSimulation.simulations_run,
        leads_simulated: lastSimulation.leads_simulated,
        net_revenue_p50: lastSimulation.distribution.net_revenue.p50,
        net_revenue_p90: lastSimulation.distribution.net_revenue.p90,
        bookings_p50: lastSimulation.distribution.bookings.p50,
        bookings_p90: lastSimulation.distribution.bookings.p90,
        conversion_rate_p50: lastSimulation.distribution.conversion_rate.p50,
        conversion_rate_p90: lastSimulation.distribution.conversion_rate.p90,
        cost_per_lead: lastSimulation.cost_assumptions.cost_per_lead,
        overhead_per_booking: lastSimulation.cost_assumptions.overhead_per_booking,
        control_variables_checked: controlChecked,
        uncontrollable_variables_checked: uncontrolChecked,
      });
      queryClient.invalidateQueries({ queryKey: ["sim-tracking-history"] });
    } catch (e) {
      alert("Failed to save snapshot: " + e.message);
    } finally {
      setSavingSnapshot(false);
    }
  };

  const controlScore = Math.round((controlChecked.length / CONTROL_VARIABLES.length) * 100);
  const uncontrolAwareness = Math.round((uncontrolChecked.length / UNCONTROLLABLE_VARIABLES.length) * 100);

  const trendIcon = (current, previous) => {
    if (!previous) return <Minus className="w-3 h-3 text-white/30" />;
    if (current > previous) return <TrendingUp className="w-3 h-3 text-[#22c55e]" />;
    if (current < previous) return <TrendingDown className="w-3 h-3 text-red-400" />;
    return <Minus className="w-3 h-3 text-white/30" />;
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex items-center justify-between flex-wrap gap-3">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-xl bg-gradient-to-br from-[#f59e0b] to-[#d97706] flex items-center justify-center">
            <SlidersHorizontal className="w-5 h-5 text-white" />
          </div>
          <div>
            <h2 className="text-lg font-extrabold tracking-tight">Variable Tracking System</h2>
            <p className="text-xs text-white/50">Track control variables you can influence and uncontrollable variables to monitor</p>
          </div>
        </div>
        <div className="flex items-center gap-2">
          {lastSimulation?.ok && (
            <button onClick={saveSnapshot} disabled={savingSnapshot}
              className="px-4 py-2 rounded-xl bg-gradient-to-r from-[#a855f7] to-[#7c3aed] text-white font-bold text-xs flex items-center gap-2 hover:brightness-110 transition disabled:opacity-50">
              {savingSnapshot ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <History className="w-3.5 h-3.5" />}
              Save Simulation Snapshot
            </button>
          )}
          <button onClick={saveChecklist} disabled={saving}
            className="px-4 py-2 rounded-xl bg-gradient-to-r from-[#f59e0b] to-[#d97706] text-white font-bold text-xs flex items-center gap-2 hover:brightness-110 transition disabled:opacity-50">
            {saving ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <Save className="w-3.5 h-3.5" />}
            Save Checklist
          </button>
        </div>
      </div>

      {/* Progress meters */}
      <div className="grid grid-cols-2 gap-4">
        <div className="rounded-xl border border-[#22c55e]/20 bg-[#22c55e]/5 p-4">
          <div className="flex items-center justify-between mb-2">
            <span className="text-xs font-bold text-[#22c55e] uppercase tracking-wider">Control Variables Active</span>
            <span className="text-2xl font-extrabold text-[#22c55e]">{controlScore}%</span>
          </div>
          <div className="h-2 rounded-full bg-white/5 overflow-hidden">
            <div className="h-full rounded-full bg-[#22c55e] transition-all" style={{ width: controlScore + "%" }} />
          </div>
          <p className="text-xs text-white/40 mt-2">{controlChecked.length} of {CONTROL_VARIABLES.length} variables actively managed</p>
        </div>
        <div className="rounded-xl border border-[#00a2ff]/20 bg-[#00a2ff]/5 p-4">
          <div className="flex items-center justify-between mb-2">
            <span className="text-xs font-bold text-[#00a2ff] uppercase tracking-wider">Uncontrollable Awareness</span>
            <span className="text-2xl font-extrabold text-[#00a2ff]">{uncontrolAwareness}%</span>
          </div>
          <div className="h-2 rounded-full bg-white/5 overflow-hidden">
            <div className="h-full rounded-full bg-[#00a2ff] transition-all" style={{ width: uncontrolAwareness + "%" }} />
          </div>
          <p className="text-xs text-white/40 mt-2">{uncontrolChecked.length} of {UNCONTROLLABLE_VARIABLES.length} variables monitored</p>
        </div>
      </div>

      {/* Control Variables */}
      <div className="rounded-2xl border border-[#22c55e]/20 bg-[#22c55e]/[0.02] p-5">
        <h3 className="font-bold text-sm mb-4 flex items-center gap-2">
          <SlidersHorizontal className="w-4 h-4 text-[#22c55e]" />
          Control Variables <span className="text-xs text-white/40 font-normal">— factors you CAN influence</span>
        </h3>
        <div className="grid md:grid-cols-2 gap-2">
          {CONTROL_VARIABLES.map((v) => {
            const checked = controlChecked.includes(v.id);
            return (
              <button key={v.id} onClick={() => toggleControl(v.id)}
                className={"flex items-start gap-3 rounded-xl border p-3 text-left transition " + (checked ? "border-[#22c55e]/40 bg-[#22c55e]/5" : "border-white/10 bg-white/[0.02] hover:border-white/20")}>
                {checked ? <CheckSquare className="w-4 h-4 text-[#22c55e] mt-0.5 shrink-0" /> : <Square className="w-4 h-4 text-white/30 mt-0.5 shrink-0" />}
                <div className="min-w-0">
                  <p className={"text-sm font-bold " + (checked ? "text-white" : "text-white/70")}>{v.label}</p>
                  <p className="text-xs text-white/40 mt-0.5">{v.desc}</p>
                  <p className="text-[10px] text-[#22c55e] font-semibold mt-1">{v.impact}</p>
                </div>
              </button>
            );
          })}
        </div>
      </div>

      {/* Uncontrollable Variables */}
      <div className="rounded-2xl border border-[#00a2ff]/20 bg-[#00a2ff]/[0.02] p-5">
        <h3 className="font-bold text-sm mb-4 flex items-center gap-2">
          <CloudRain className="w-4 h-4 text-[#00a2ff]" />
          Uncontrollable Variables <span className="text-xs text-white/40 font-normal">— factors to monitor but cannot change</span>
        </h3>
        <div className="grid md:grid-cols-2 gap-2">
          {UNCONTROLLABLE_VARIABLES.map((v) => {
            const checked = uncontrolChecked.includes(v.id);
            return (
              <button key={v.id} onClick={() => toggleUncontrol(v.id)}
                className={"flex items-start gap-3 rounded-xl border p-3 text-left transition " + (checked ? "border-[#00a2ff]/40 bg-[#00a2ff]/5" : "border-white/10 bg-white/[0.02] hover:border-white/20")}>
                {checked ? <CheckSquare className="w-4 h-4 text-[#00a2ff] mt-0.5 shrink-0" /> : <Square className="w-4 h-4 text-white/30 mt-0.5 shrink-0" />}
                <div className="min-w-0">
                  <p className={"text-sm font-bold " + (checked ? "text-white" : "text-white/70")}>{v.label}</p>
                  <p className="text-xs text-white/40 mt-0.5">{v.desc}</p>
                  <p className="text-[10px] text-[#00a2ff] font-semibold mt-1">{v.impact}</p>
                </div>
              </button>
            );
          })}
        </div>
      </div>

      {/* Simulation History */}
      <div className="rounded-2xl border border-white/10 bg-white/[0.02] p-5">
        <h3 className="font-bold text-sm mb-4 flex items-center gap-2">
          <History className="w-4 h-4 text-[#a855f7]" />
          Simulation Run History
          {history.length > 0 && <span className="text-xs text-white/40 font-normal">— {history.length} snapshots saved</span>}
        </h3>
        {historyLoading ? (
          <div className="flex items-center justify-center py-8"><Loader2 className="w-5 h-5 animate-spin text-white/30" /></div>
        ) : history.length === 0 ? (
          <p className="text-sm text-white/40 text-center py-8">No simulation snapshots saved yet. Run a simulation and click "Save Simulation Snapshot" to start tracking trends over time.</p>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-sm">
              <thead className="text-white/40 text-xs uppercase">
                <tr>
                  <th className="text-left font-medium px-3 py-2">Date</th>
                  <th className="text-right font-medium px-3 py-2">Sims</th>
                  <th className="text-right font-medium px-3 py-2">Leads</th>
                  <th className="text-right font-medium px-3 py-2">P50 Net Rev</th>
                  <th className="text-right font-medium px-3 py-2">P90 Net Rev</th>
                  <th className="text-right font-medium px-3 py-2">P50 Bookings</th>
                  <th className="text-right font-medium px-3 py-2">P90 Bookings</th>
                  <th className="text-right font-medium px-3 py-2">Controls</th>
                  <th className="text-center font-medium px-3 py-2">Trend</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-white/5">
                {history.map((h, i) => {
                  const prev = history[i + 1];
                  return (
                    <tr key={h.id} className="hover:bg-white/[0.02]">
                      <td className="px-3 py-2.5 text-white/60 whitespace-nowrap">{new Date(h.created_date).toLocaleDateString("en-US", { month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" })}</td>
                      <td className="px-3 py-2.5 text-right font-mono text-white/60">{h.simulations_run}</td>
                      <td className="px-3 py-2.5 text-right font-mono text-white/60">{h.leads_simulated}</td>
                      <td className="px-3 py-2.5 text-right font-mono text-[#00a2ff]">${(h.net_revenue_p50 || 0).toLocaleString()}</td>
                      <td className="px-3 py-2.5 text-right font-mono text-[#22c55e] font-bold">${(h.net_revenue_p90 || 0).toLocaleString()}</td>
                      <td className="px-3 py-2.5 text-right font-mono text-white/60">{h.bookings_p50}</td>
                      <td className="px-3 py-2.5 text-right font-mono text-[#22c55e]">{h.bookings_p90}</td>
                      <td className="px-3 py-2.5 text-right">
                        <span className="text-xs font-bold px-2 py-0.5 rounded bg-[#22c55e]/10 text-[#22c55e]">{(h.control_variables_checked || []).length}/10</span>
                      </td>
                      <td className="px-3 py-2.5 text-center">{trendIcon(h.net_revenue_p90, prev?.net_revenue_p90)}</td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
}